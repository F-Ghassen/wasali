#!/usr/bin/env node
/**
 * Regenerates lib/flags/flagSvgData.generated.ts from the SVG files in assets/flags/.
 *
 * Run after adding/updating a flag in assets/flags/<iso-code>.svg:
 *   node scripts/generate-flag-svgs.js
 *
 * To add a new country: download its flag SVG (e.g. from flagcdn.com/<code>.svg,
 * MIT-licensed flag-icons project), save it as assets/flags/<code>.svg, ensure it has
 * a `viewBox` attribute (add one derived from width/height if missing — some flagcdn
 * SVGs omit it, which breaks scaling), then re-run this script and add the country to
 * COUNTRY_CODE_MAP in lib/flagImages.ts.
 */
const fs = require('fs');
const path = require('path');

const SRC_DIR = path.join(__dirname, '..', 'assets', 'flags');
const OUT_FILE = path.join(__dirname, '..', 'lib', 'flags', 'flagSvgData.generated.ts');

const files = fs.readdirSync(SRC_DIR).filter((f) => f.endsWith('.svg')).sort();

let out = '// Auto-generated by scripts/generate-flag-svgs.js from assets/flags/*.svg\n';
out += '// (source: flagcdn.com, MIT-licensed flag-icons project). Do not edit by hand —\n';
out += '// update the .svg file and re-run the script instead.\n';
out += 'export const FLAG_SVG: Record<string, string> = {\n';

for (const file of files) {
  const code = path.basename(file, '.svg');
  const svg = fs.readFileSync(path.join(SRC_DIR, file), 'utf8').trim();
  if (!svg.includes('viewBox')) {
    throw new Error(`assets/flags/${file} is missing a viewBox attribute — add one before regenerating`);
  }
  const escaped = svg.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
  out += `  ${code}: \`${escaped}\`,\n`;
}

out += '};\n';

fs.writeFileSync(OUT_FILE, out);
console.log(`Wrote ${files.length} flags to ${path.relative(process.cwd(), OUT_FILE)}`);
